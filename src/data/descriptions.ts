/** Derives the numerology-style rank key ("ace"|"2"..."10"|page|knight|queen|king) from a Russian card name. */
function rankKeyFromName(name: string): string | null {
  const firstWord = name.split(" ")[0];
  const map: Record<string, string> = {
    Туз: "ace",
    Паж: "page",
    Рыцарь: "knight",
    Королева: "queen",
    Король: "king",
  };
  if (map[firstWord]) return map[firstWord];
  if (/^\d+$/.test(firstWord)) return firstWord;
  return null;
}

function buildMinorArcanaExtra(name: string, suit?: string): string | null {
  if (!suit || !(suit in SUIT_CLAUSE)) return null;
  const rankKey = rankKeyFromName(name);
  const rankClause = rankKey ? RANK_CLAUSE[rankKey] : null;
  return rankClause ? `${SUIT_CLAUSE[suit]} ${rankClause}` : SUIT_CLAUSE[suit];
}

function buildFullMeaning(
  system: DeckSystem,
  name: string,
  short: string,
  suit?: string
): string {
  const bespoke = SYSTEM_EXTRA[system]?.[name];
  if (bespoke) return `${name} — ${short}. ${bespoke}`;

  const minorExtra = system.startsWith("tarot") ? buildMinorArcanaExtra(name, suit) : null;
  if (minorExtra) return `${name} — ${short}. ${minorExtra}`;

  const intro = SYSTEM_INTRO[system];
  return `${name} — ${short}. ${intro} Прислушайтесь к этому знаку: он подсказывает, куда направить внимание сегодня и какие качества активировать в себе.`;
}

function buildDescriptionMap(system: DeckSystem): Record<string, SymbolDescription> {
  const out: Record<string, SymbolDescription> = {};
  for (const symbol of DECK_REGISTRY[system].symbols) {
    const short = symbol.meaning.trim();
    out[symbol.name] = {
      shortMeaning: short,
      fullMeaning: buildFullMeaning(system, symbol.name, short, symbol.suit),
      keywords: keywordsFromMeaning(short),
    };
  }
  return out;
}

