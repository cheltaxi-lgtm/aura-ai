export function buildGuestTeaserUserPrompt(input: {
  question: string;
  cards: Array<{
    name: string;
    positionLabel: string;
    reversed: boolean;
    meaningHint: string;
  }>;
}): string {
  const lines = input.cards.map((c, i) => {
    const rev = c.reversed ? " (перевёрнутая)" : "";
    const hint = c.meaningHint.trim() || "символ открыт";
    return `${i + 1}) ${c.name}${rev} — ${hint}`;
  });
  const names = input.cards.map((c) => c.name).join(", ");
  return [
    `Вопрос: ${input.question}`,
    "Три карты (назови все три имени во втором предложении; позиции не перечисляй):",
    ...lines,
    `Обязательные имена в тексте: ${names}.`,
    "Напиши ровно 3 предложения по правилам.",
  ].join("\n");
}
