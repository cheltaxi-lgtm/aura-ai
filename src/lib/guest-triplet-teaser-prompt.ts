export function buildGuestTeaserUserPrompt(input: {
  question: string;
  cards: Array<{ name: string; positionLabel: string; reversed: boolean }>;
}): string {
  const lines = input.cards.map((c) => {
    const rev = c.reversed ? " (перевёрнутая)" : "";
    return `${c.positionLabel}: ${c.name}${rev}`;
  });
  return [
    `Вопрос: ${input.question}`,
    "Карты (только контекст, не каркас ответа):",
    ...lines,
    "Напиши ориентир по правилам: сначала ситуация человека, потом конфликт по этому вопросу, без перечисления позиций.",
  ].join("\n");
}
