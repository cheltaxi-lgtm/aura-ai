export function buildGuestTeaserUserPrompt(input: {
  question: string;
  cards: Array<{
    name: string;
    positionLabel: string;
    reversed: boolean;
    meaningHint: string;
  }>;
  repairReason?: string;
}): string {
  const lines = input.cards.map((c, i) => {
    const rev = c.reversed ? " (перевёрнутая)" : "";
    const hint = c.meaningHint.trim() || "символ открыт";
    return `${i + 1}) ${c.name}${rev} — ${hint}`;
  });
  const names = input.cards.map((c) => c.name).join(", ");
  const parts = [
    `Вопрос: ${input.question}`,
    "Три карты (во втором предложении назови все три имени точно; позиции не перечисляй):",
    ...lines,
    `Обязательные имена в тексте: ${names}.`,
    "Напиши ровно 3 предложения по правилам.",
  ];
  if (input.repairReason) {
    parts.push(
      `Предыдущий черновик отклонён (${input.repairReason}). Перепиши заново: без этой ошибки, с именами всех трёх карт.`
    );
  }
  return parts.join("\n");
}
