export function buildGuestTeaserUserPrompt(input: {
  question: string;
  cards: Array<{
    name: string;
    positionLabel: string;
    reversed: boolean;
    meaningHint: string;
  }>;
}): string {
  const lines = input.cards.map((c) => {
    const rev = c.reversed ? " (перевёрнутая)" : "";
    const hint = c.meaningHint.trim() || "символ открыт";
    return `${c.positionLabel}: ${c.name}${rev} — ${hint}`;
  });
  return [
    `Вопрос: ${input.question}`,
    "Карты и их краткие значения (вплети все три мотива; назови ровно одну карту; не перечисляй позиции):",
    ...lines,
    "Напиши ориентир: сначала ситуация человека, затем конфликт вопроса через эти карты, без каркаса прошлого/настоящего/будущего.",
  ].join("\n");
}
