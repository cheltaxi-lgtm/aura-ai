function relatedFor(extra: PalmSeoRelated[]): PalmSeoRelated[] {
  const seen = new Set<string>();
  const out: PalmSeoRelated[] = [];
  for (const item of [...extra, ...CTA_RELATED]) {
    if (seen.has(item.href)) continue;
    seen.add(item.href);
    out.push(item);
  }
  return out;
}

