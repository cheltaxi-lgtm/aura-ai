export function getSeoArticleBySlug(slug: string): SeoArticle | undefined {
  return SEO_ARTICLES.find((a) => a.slug === slug);
}

export function getAllSeoArticleSlugs(): string[] {
  return SEO_ARTICLES.map((a) => a.slug);
}

export function getArticleForIntent(intentSlug: string): SeoArticle | undefined {
  return SEO_ARTICLES.find((a) => a.intentSlugs.includes(intentSlug));
}
