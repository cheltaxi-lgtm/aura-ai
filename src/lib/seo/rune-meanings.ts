export const RUNE_MEANINGS: RuneMeaning[] = RUNE_SYMBOLS.map((symbol) => {
  const slug = symbol.slug ?? symbol.name.toLowerCase();
  const data = RUNE_MEANING_DATA[slug];
  return {
    slug,
    name: symbol.name,
    keyword: data?.keyword ?? symbol.meaning,
    general: data?.general ?? symbol.meaning,
    love: data?.love ?? "",
    money: data?.money ?? "",
  };
});

export function getRuneMeaningBySlug(slug: string): RuneMeaning | undefined {
  return RUNE_MEANINGS.find((r) => r.slug === slug);
}

export function getAllRuneMeaningSlugs(): string[] {
  return RUNE_MEANINGS.map((r) => r.slug);
}
