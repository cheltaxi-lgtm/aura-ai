const CTA_RELATED: AuraSeoRelated[] = [
  { href: "/aura", title: "Снять ауру по фото" },
  { href: "/aura/cveta", title: "Значение цветов ауры" },
  { href: "/aura/chakry", title: "Семь чакр" },
  { href: "/aura/sloi", title: "Семь слоёв поля" },
];

function relatedFor(extra: AuraSeoRelated[]): AuraSeoRelated[] {
  const seen = new Set<string>();
  const out: AuraSeoRelated[] = [];
  for (const item of [...extra, ...CTA_RELATED]) {
    if (seen.has(item.href)) continue;
    seen.add(item.href);
    out.push(item);
  }
  return out;
}

