export const HD_PROFILE_SEO: readonly HdProfileSeo[] = Object.keys(PROFILE_NAMES_RU).map(
  (profile) => {
    const slug = profile.replace("/", "-");
    const name = PROFILE_NAMES_RU[profile]!;
    const blurb = PROFILE_BLURBS[profile]!;
    return {
      slug,
      profile,
      title: `Профиль ${profile} «${name}» в Дизайне Человека`,
      metaDescription: `Профиль ${profile} (${name}) в Дизайне Человека: характер, линии, жизненные этапы, работа и отношения. Рассчитайте свой профиль бесплатно по дате, времени и месту рождения.`,
      ...blurb,
    };
  }
);

export function hdTypeSeoBySlug(slug: string): HdTypeSeo | undefined {
  return HD_TYPE_SEO.find((t) => t.slug === slug);
}

export function hdProfileSeoBySlug(slug: string): HdProfileSeo | undefined {
  return HD_PROFILE_SEO.find((p) => p.slug === slug);
}

export function hdTypeSlug(type: HdTypeKey): string {
  return HD_TYPE_SEO.find((t) => t.type === type)?.slug ?? type;
}

