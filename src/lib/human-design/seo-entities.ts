/** Opposite gate on the mandala wheel — the classical «harmonic» counterpart. */
function harmonicGate(gate: number): number | null {
  const idx = GATE_ORDER.indexOf(gate);
  if (idx < 0) return null;
  return GATE_ORDER[(idx + 32) % 64] ?? null;
}

