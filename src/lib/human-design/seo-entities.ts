const CENTER_SLUGS: Record<HdCenterKey, string> = {
  head: "golovnoj",
  ajna: "adzhna",
  throat: "gorlovoj",
  g: "g-centr",
  heart: "ego",
  sacral: "sakralnyj",
  solar: "emocionalnyj",
  spleen: "selezyonochnyj",
  root: "kornevoj",
};

export const CENTER_SEO_SLUGS = Object.values(CENTER_SLUGS);

export function centerSeo(slug: string): HdCenterSeo | null {
  const entry = (Object.entries(CENTER_SLUGS) as [HdCenterKey, string][]).find(
    ([, s]) => s === slug
  );
  if (!entry) return null;
  const [center] = entry;
  const name = CENTER_NAMES_RU[center];
  const essay = CENTER_ESSAY[center];
  const gates = Object.entries(GATE_CENTERS)
    .filter(([, c]) => c === center)
    .map(([g]) => Number(g));
  return {
    center,
    slug,
    name,
    title: `${name} центр в Дизайне Человека`,
    metaDescription: `${name} центр: тема «${essay.theme}». Что даёт определённый и открытый ${name} центр, ворота центра (${gates.join(", ")}), практические рекомендации.`,
    intro: `${name} центр отвечает за тему: ${essay.theme}. В бодиграфе он может быть определённым (закрашенным) или открытым (белым) — и это два совершенно разных способа проживать одну тему.`,
    definedBody: essay.defined,
    openBody: essay.open,
    faq: [
      {
        q: `Что значит определённый ${name} центр?`,
        a: essay.defined,
      },
      {
        q: `Что значит открытый ${name} центр?`,
        a: essay.open,
      },
      {
        q: "Как узнать, определён ли у меня этот центр?",
        a: "Рассчитайте бесплатную карту по дате, времени и месту рождения — определённые центры будут закрашены на бодиграфе.",
      },
    ],
  };
}

