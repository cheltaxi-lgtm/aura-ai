import {
  CENTER_NAMES_RU,
  CHANNELS,
  GATE_CENTERS,
  GATE_NAMES_RU,
} from "./constants";
import type { HdCenterKey } from "./types";

export interface HdEntitySection {
  title: string;
  body: string;
}

export interface HdEntityFaq {
  q: string;
  a: string;
}

export interface HdGateSeo {
  gate: number;
  slug: string;
  name: string;
  center: HdCenterKey;
  title: string;
  metaDescription: string;
  intro: string;
  sections: HdEntitySection[];
  faq: HdEntityFaq[];
}

const LINE_THEMES = [
  "исследование и фундамент",
  "естественный талант и призвание",
  "опыт через пробу и ошибку",
  "влияние через дружбу и сети",
  "проекции и практичные решения",
  "ролевая модель и мудрость",
];

export function gateSeo(gate: number): HdGateSeo | null {
  const name = GATE_NAMES_RU[gate];
  const center = GATE_CENTERS[gate];
  if (!name || !center) return null;
  const centerName = CENTER_NAMES_RU[center];
  const channels = CHANNELS.filter((c) => c.gates.includes(gate));
  const channelList = channels
    .map((c) => `канал ${c.gates[0]}-${c.gates[1]} «${c.nameRu}»`)
    .join(", ");

  return {
    gate,
    slug: String(gate),
    name,
    center,
    title: `Ворота ${gate} — ${name}`,
    metaDescription: `Ворота ${gate} «${name}» в Дизайне Человека: значение, центр ${centerName}, линии, каналы (${channelList}). Узнайте, активированы ли они в вашей карте.`,
    intro:
      `Ворота ${gate} «${name}» расположены в центре ${centerName} и задают одну из 64 тем человеческого опыта. ` +
      `Если эти ворота активированы в вашей карте, тема «${name}» становится устойчивой частью вашей природы — через неё вы воспринимаете мир и влияете на других.`,
    sections: [
      {
        title: "Значение ворот",
        body:
          `Тема ворот ${gate} — «${name}». Энергия этих ворот окрашивает работу центра ${centerName}: ` +
          `она проявляется как повторяющийся мотив в решениях, отношениях и работе. Активированные ворота — это то, что вы несёте в мир постоянно, независимо от обстоятельств.`,
      },
      {
        title: "Каналы и связи",
        body:
          `Ворота ${gate} образуют ${channelList}. Когда у человека активированы оба ворота канала, канал становится определённым — это постоянная сила, которая определяет центры на обоих концах. ` +
          `Если активированы только ворота ${gate}, это «висячие» ворота: вы заметно притягиваете людей, у которых активирована вторая половина канала.`,
      },
      {
        title: "Шесть линий",
        body:
          `Планета, активирующая ворота, всегда стоит в одной из шести линий, и линия меняет вкус темы: ` +
          LINE_THEMES.map((t, i) => `линия ${i + 1} — ${t}`).join("; ") +
          `. Точную линию показывает расчёт карты по дате, времени и месту рождения.`,
      },
    ],
    faq: [
      {
        q: `Что значат ворота ${gate} в карте?`,
        a: `Активированные ворота ${gate} «${name}» делают эту тему постоянной частью вашей природы. Они работают через центр ${centerName} и ищут вторую половину своего канала в других людях.`,
      },
      {
        q: "Что такое висячие ворота?",
        a: "Это активированные ворота без второй половины канала. Они создают здоровое притяжение к людям, которые дополняют канал, — так рождается электромагнетика в паре.",
      },
      {
        q: "Как узнать, активированы ли у меня эти ворота?",
        a: "Рассчитайте бесплатную карту Дизайна Человека по дате, времени и месту рождения — все активные ворота будут подсвечены на бодиграфе.",
      },
    ],
  };
}

export interface HdChannelSeo {
  key: string;
  slug: string;
  name: string;
  gates: [number, number];
  centers: [HdCenterKey, HdCenterKey];
  title: string;
  metaDescription: string;
  intro: string;
  sections: HdEntitySection[];
  faq: HdEntityFaq[];
}

export function channelSeo(key: string): HdChannelSeo | null {
  const def = CHANNELS.find((c) => `${c.gates[0]}-${c.gates[1]}` === key);
  if (!def) return null;
  const [gA, gB] = def.gates;
  const [cA, cB] = def.centers;
  return {
    key,
    slug: key,
    name: def.nameRu,
    gates: def.gates,
    centers: def.centers,
    title: `Канал ${key} — ${def.nameRu}`,
    metaDescription: `Канал ${key} «${def.nameRu}» в Дизайне Человека: ворота ${gA} и ${gB}, центры ${CENTER_NAMES_RU[cA]} и ${CENTER_NAMES_RU[cB]}. Значение определённого канала и висячих ворот.`,
    intro:
      `Канал ${key} «${def.nameRu}» соединяет центр ${CENTER_NAMES_RU[cA]} и центр ${CENTER_NAMES_RU[cB]} ` +
      `через ворота ${gA} «${GATE_NAMES_RU[gA]}» и ворота ${gB} «${GATE_NAMES_RU[gB]}». ` +
      `Определённый канал — это постоянная, надёжная сила: он окрашивает всю жизнь человека.`,
    sections: [
      {
        title: "Энергия канала",
        body:
          `«${def.nameRu}» объединяет темы «${GATE_NAMES_RU[gA]}» и «${GATE_NAMES_RU[gB]}» в единый поток. ` +
          `Когда канал определён, оба центра — ${CENTER_NAMES_RU[cA]} и ${CENTER_NAMES_RU[cB]} — становятся определёнными: их энергия стабильна и доступна вам всегда, а не зависит от окружения.`,
      },
      {
        title: "Если активирована только половина",
        body:
          `Ворота ${gA} без ${gB} (или наоборот) — это висячие ворота. Тема «${def.nameRu}» тогда раскрывается через других людей: ` +
          `вы устойчиво притягиваете носителей второй половины канала, и в паре возникает электромагнетика — сильное притяжение и взаимное дополнение.`,
      },
      {
        title: "Канал в совместимости",
        body:
          `В композите двух карт канал ${key} может сложиться из половин двух людей. ` +
          `Такие электромагнетические каналы — главные точки искры и притирки в отношениях: они дают и сильное влечение, и главные уроки пары.`,
      },
    ],
    faq: [
      {
        q: `Что даёт определённый канал ${key}?`,
        a: `Постоянную силу «${def.nameRu}» и определённость центров ${CENTER_NAMES_RU[cA]} и ${CENTER_NAMES_RU[cB]}. Это устойчивая часть личности, которая не зависит от чужого влияния.`,
      },
      {
        q: "Чем канал отличается от ворот?",
        a: "Ворота — одна тема, канал — устойчивый поток между двумя центрами. Именно определённые каналы формируют тип, авторитет и определённость карты.",
      },
      {
        q: "Как проверить свои каналы?",
        a: "Рассчитайте карту бесплатно: определённые каналы будут выделены на бодиграфе, а висячие ворота видны по половинкам каналов.",
      },
    ],
  };
}

