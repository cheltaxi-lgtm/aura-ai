/** Classify the channel's stream by real mechanics: motor→throat = manifestation, sacral = generation, etc. */
function channelStreamType(cA: HdCenterKey, cB: HdCenterKey): string {
  const motorA = (MOTOR_CENTERS as readonly string[]).includes(cA);
  const motorB = (MOTOR_CENTERS as readonly string[]).includes(cB);
  const throatA = cA === "throat" || cB === "throat";
  const sacral = cA === "sacral" || cB === "sacral";
  if (sacral && throatA) {
    return "Это генерирующий канал: сакральная энергия напрямую выходит в проявление. Его сила — в честном отклике, который сразу становится действием.";
  }
  if ((motorA || motorB) && throatA) {
    return "Это манифестирующий канал: мотор соединён с Горлом, поэтому энергия способна проявляться в действие напрямую. Его сила — в инициации и информировании.";
  }
  if (motorA || motorB) {
    return "Это двигательный канал: он несёт моторную энергию, но без прямого выхода в Горло — его сила раскрывается через отклик или приглашение, а не через прямую инициацию.";
  }
  return "Это проецируемый канал: без мотора его энергия — не сила действия, а качество осознанности. Он раскрывается через признание и приглашение.";
}

