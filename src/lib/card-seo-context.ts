export function getCardContextualMeanings(card: TarotCard): CardContextualMeanings {
  const major = MAJOR_CONTEXT[card.name];
  if (major) return major;

  const suit = card.suit ?? "cups";
  return {
    general: card.meaning,
    love: `${card.name} в любви: ${SUIT_LOVE[suit] ?? card.meaning}`,
    money: `${card.name} в финансах: ${SUIT_MONEY[suit] ?? card.meaning}`,
    self: `${card.name} в самопознании: ${SUIT_SELF[suit] ?? card.meaning}`,
    reversed: "Перевёрнутое значение зависит от соседних карт — мастер уточнит в раскладе.",
  };
}

