import type { PromptUserContext } from "./types";
import {
  buildClientGenderInstruction,
  resolveClientGender,
} from "@/lib/russian-name-gender";
import { CLIENT_VS_SUBJECT_NAME_RULE } from "@/lib/custom-question-scope";

/** Правила местоимений: клиент vs люди из вопроса. */
export function buildGenderPronounBlock(
  user: PromptUserContext,
  lastUserMessage?: string
): string {
  const firstName = (user.name ?? "").trim().split(/\s+/)[0] || "друг";
  const gender = resolveClientGender(user.gender, firstName);
  const lines: string[] = [
    buildClientGenderInstruction({ gender, firstName }),
  ];

  const msg = (lastUserMessage ?? user.mainQuestion ?? "").toLowerCase();

  if (/\bжена\b|\bжену\b|\bжене\b|\bсупруг[а]?\b/.test(msg) && !/\bмуж\b|\bмужа\b/.test(msg)) {
    lines.push(
      "- В вопросе речь о жене клиента — называй её «она», «жена», женский род. Клиента не называй «она»."
    );
  }
  if (/\bмуж\b|\bмужа\b|\bмужу\b/.test(msg)) {
    lines.push(
      "- В вопросе речь о муже клиента — «он», «муж», мужской род. Клиента не называй «он» в смысле супруга."
    );
  }
  if (
    /\bона\b|\bон\b|\bпартнёр|\bпартнёрш|\bлюбовниц|\bлюбовник/.test(msg) ||
    /жив(?:а|о)?\s+ли|пропал|без вести/.test(msg)
  ) {
    lines.push(
      "- Различай: «ты» = клиент, «он/она» = тот о ком спрашивают. Никогда не путай их пол и роли."
    );
    lines.push(`- ${CLIENT_VS_SUBJECT_NAME_RULE}`);
  }

  return lines.join("\n");
}

