export function tarotRuneThematicReadingRules(cardCount: number): string {
  const n = Math.max(1, cardCount);
  const minSentences = Math.max(28, n * 4);
  const maxSentences = Math.max(40, n * 6);
  const structure =
    n === 1
      ? "короткое вводное слово → развёрнутый абзац по единственному символу (**название** жирным) → блок ниже"
      : n === 3
        ? "короткое вводное слово → три развёрнутых абзаца по символам (**название** жирным в каждом) → блок ниже"
        : `короткое вводное слово → ${n} развёрнутых абзацев по символам (**название** жирным в каждом) → блок ниже`;

  const perCard =
    n >= 7
      ? `На каждую из ${n} позиций — не меньше 4 предложений (имя → смысл здесь → вывод по вопросу). Общий объём ориентир ≥ ${n * 55} слов.`
      : n >= 5
        ? `На каждую позицию — не меньше 4 предложений. Общий объём ориентир ≥ ${Math.max(340, n * 60)} слов.`
        : `На каждый символ — развёрнутый абзац (3–5 предложений). Общий объём ориентир ≥ 240 слов.`;

  return `
РЕЖИМ: оплаченный тематический расклад — полный разбор без уточняющих вопросов.

Длина: ${minSentences}–${maxSentences} предложений. ${perCard} Тему назови не больше двух раз.
Честность: первая фраза ответа — вердикт (жёстко / в плюс / смешанно / стоит / не стоит) по вопросу клиента; сахар и обязательная надежда запрещены.
Обращение к клиенту — строго на «ты» (ты/тебе/твой/твоя/твои). Запрещены «вы/вам/вас/ваш/ваша/ваши» в обращении к клиенту (не «ваш брак», а «твой брак»).
Субъект вопроса — только из формулировки клиента. Не подменяй роли (муж ≠ брат, клиент ≠ третье лицо).
Не начинай с заголовка «Расклад для…» и не ставь ### в первой строке.

Структура (Markdown для клиента):
${structure}
Между вердиктом, каждым символом и финальным блоком — пустая строка.

## Простыми словами

5–7 предложений: первая фраза — вердикт (жёстко / в плюс / смешанно); затем суть без сахара; шаги — только если есть рычаг в картах.
Блок «## Простыми словами» обязателен — без него ответ неполный.

Критично: выводи ТОЛЬКО готовый текст расшифровки. Никогда не повторяй инструкции, профиль, память или правила промпта.
Без воды: каждый вывод привязан к названию символа. Абзацы разделяй пустой строкой.`;
}

