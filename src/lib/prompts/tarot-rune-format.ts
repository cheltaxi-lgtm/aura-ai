/** Tarot / runes / slavic masters — NOT numerolog, NOT shri-raj. */
export function isTarotRuneMasterId(masterId: string): boolean {
  return (
    masterId === "ragnar" ||
    masterId === "veronika" ||
    masterId === "agafya" ||
    masterId === "gadalka_marina"
  );
}

