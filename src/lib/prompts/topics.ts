/** Detect heavy topics from user message for optional injection. */
export function detectTopics(text: string): TopicKey[] {
  const t = text.toLowerCase();
  const found = new Set<TopicKey>();
  if (/смерт|умр|похорон|ушел|ушла|потерял.*близк/.test(t)) found.add("death");
  if (/болезн|рак|диагноз|больниц|операц|здоров|онколог/.test(t)) found.add("illness");
  if (/измен|предат|обман|невер|любовниц|любовник/.test(t)) found.add("betrayal");
  if (/порч|сглаз|проклят|наговор|ведьм|черн.*маг/.test(t)) found.add("curse");
  if (/денег|долг|банкрот|бедн|крах|увольн|зарплат|доход/.test(t)) found.add("money_loss");
  if (/развод|расста|любов|отношен|ревност|брак|партнёр|партнер/.test(t)) found.add("love_crisis");
  if (/приворот|отворот|ритуал|обряд.*темн/.test(t)) found.add("dark_magic");
  if (/враг|конкурент|соперник|интриг|предател/.test(t)) found.add("enemies");
  if (/одинок|депресс|пустот|апати|тоск|не вижу смысл|выгор/.test(t)) found.add("loneliness");
  if (/работ|карьер|начальник|коллег|бизнес|проект|увольн/.test(t)) found.add("career");
  if (/семь|род|мама|мать|папа|отец|дети|ребён|ребенок|родител/.test(t)) found.add("family");
  if (/знак|предназнач|смысл жизн|путь|судьб|зов|послан/.test(t)) found.add("spiritual");
  return [...found];
}

export function topicsFromIntention(intention?: string | null): TopicKey[] {
  if (!intention?.trim()) return [];
  const key = INTENTION_TOPICS[intention.trim()];
  return key ? [key] : [];
}

export function mergeTopics(message: string, intention?: string | null): TopicKey[] {
  const fromMessage = detectTopics(message);
  // life_death has its own safety protocol — do not inject generic death handlers.
  const filtered =
    intention?.trim() === "life_death"
      ? fromMessage.filter((t) => t !== "death")
      : fromMessage;
  const merged = new Set<TopicKey>([...filtered, ...topicsFromIntention(intention)]);
  return [...merged];
}

export function buildTopicBlock(character: CharacterKey, topics: TopicKey[]): string {
  if (!topics.length) return "";
  const unique = [...new Set(topics)];
  const lines = unique
    .map((topic) => TOPIC_HANDLERS[topic]?.[character])
    .filter(Boolean);
  if (!lines.length) return "";
  return `\nАКТУАЛЬНАЯ ТЕМА ВОПРОСА (вывод только по символам расклада):\n${lines.join("\n\n")}`;
}

