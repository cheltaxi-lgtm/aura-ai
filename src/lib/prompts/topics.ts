/** Detect heavy topics from user message for optional injection. */
export function detectTopics(text: string): TopicKey[] {
  const t = text.toLowerCase();
  const found: TopicKey[] = [];
  if (/смерт|умр|похорон|ушел|ушла|потерял.*близк/.test(t)) found.push("death");
  if (/болезн|рак|диагноз|больниц|операц|здоров/.test(t)) found.push("illness");
  if (/измен|предат|обман|невер|любовниц|любовник/.test(t)) found.push("betrayal");
  if (/porч|сглаз|проклят|наговор|ведьм|черн.*маг/.test(t)) found.push("curse");
  if (/денег|долг|банкрот|бедн|крах|увольн/.test(t)) found.push("money_loss");
  if (/развод|расста|любов|отношен|одинок|ревност/.test(t)) found.push("love_crisis");
  if (/приворот|отворот|ритуал|обряд.*темн/.test(t)) found.push("dark_magic");
  return found;
}

export function buildTopicBlock(character: CharacterKey, topics: TopicKey[]): string {
  if (!topics.length) return "";
  const lines = topics
    .map((topic) => TOPIC_HANDLERS[topic]?.[character])
    .filter(Boolean);
  if (!lines.length) return "";
  return `\nАКТУАЛЬНАЯ ТЕМА ВОПРОСА:\n${lines.join("\n\n")}`;
}
