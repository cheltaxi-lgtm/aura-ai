export function explainPosition(position: BodyPosition): string {
  const theme = BODY_THEMES[position.key] ?? russianPlanetLabel(position.key).toLowerCase();
  const house = position.house ? ` Дом ${position.house} в традиции связывают с областью, где эта тема может быть заметнее.` : "";
  const retrograde = position.retrograde ? " Символ ℞ отмечает видимое обратное движение; в астрологической традиции это иногда связывают с более внутренним способом проживать тему." : "";
  return `${position.name} в ${position.sign}: в астрологической традиции это связывают с темой «${theme}», которая может проявляться через стиль этого знака.${house}${retrograde}`;
}

export function explainAspect(aspect: AspectRow): string {
  const orb = aspect.orb == null ? "" : ` Орб ${aspect.orb.toFixed(2)}° описывает близость к точной геометрии.`;
  return `${aspect.label} связывает ${aspect.first} и ${aspect.second}: это может подсветить, как две символические темы взаимодействуют, без вывода о результате.${orb}`;
}

export function explainPattern(pattern: PatternRow): string {
  return `${pattern.label} — геометрический рисунок из ${pattern.planets.join(", ")}. В астрологической традиции его используют как способ заметить повторяющуюся связку тем, а не как самостоятельный прогноз.`;
}

export function explainMidpoint(point: MidpointRow): string {
  return `Мидпойнт ${point.pair} — математическая середина между двумя положениями. Его используют как дополнительную точку наблюдения; ${point.sign} — знак этой рассчитанной середины.`;
}

export function explainGraha(chart: VedicChart, key: VedicGrahaKey): string | null {
  const position = chart.positions[key];
  if (!position) return null;
  const theme = GRAHA_THEMES[key];
  const lagnaGuard = key === "ascendant" && !chart.hasExactLagna
    ? " Для неизвестного времени лагна не интерпретируется."
    : "";
  return `${russianGrahaLabel(key)} в ${position.rashi.name}: в джйотиш это связывают с темой «${theme}», которая может проявляться через качества этого раши. Накшатра ${position.nakshatra.name}; пада ${position.nakshatra.pada} уточняет традиционный контекст.${lagnaGuard}`;
}

export function explainVedicHouse(number: number, sign: string, grahaCount: number): string {
  const contents = grahaCount
    ? ` В этом доме рассчитано грах: ${grahaCount}.`
    : " В нём нет показанных грах; это не означает отсутствия соответствующей темы.";
  return `Дом ${number} начинается в ${sign}. При известной лагне в джйотиш дома используют как традиционную карту жизненных областей, которая может помочь организовать наблюдения.${contents}`;
}

export function explainDasha(chart: VedicChart): string {
  const current = chart.dasha.current;
  if (!current) return "Текущая махадаша не рассчитана; без неё не стоит делать выводы о периоде.";
  const confidence = chart.dasha.authoritative ? "" : " Расчёт содержит технические предупреждения, поэтому используйте его только как справочный контекст.";
  return `Текущая махадаша ${russianGrahaLabel(current.lord)} длится с ${current.startDate.slice(0, 10)} по ${current.endDate.slice(0, 10)}. В традиции её связывают с фокусом периода, но не с неизбежными событиями.${confidence}`;
}
